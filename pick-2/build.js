// Writes design.js: the shelter and stove instructions from ../procedures, in the build order
// on the shelter page, with every size filled in, so the checklist works with no signal.
// Run from the repo root after changing a procedure: node pick-2/build.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const L = require('../engine/lib.js');
const reg = L.byId(require('../procedures/index.js').load());
const params = require('../procedures/project.js').params();
const { CHANGES, relative } = require('./site.js');
const C = require('../procedures/catalog.js');
const photos = require('../procedures/photos.js');

// The build order from shelter/index.html, with the camp tools made first.
const ORDER = ['plan.make-tools', 'shelter.choose-site', 'shelter.frame', 'shelter.roof-insulate', 'shelter.walls',
  'plan.stove-stage-one', 'stove.first-firing', 'shelter.fit-out', 'plan.stove-stage-two', 'shelter.earth-skirt', 'shelter.snow-bank'];

function build() {
  const procs = {};
  const used = new Set();
  // Site changes first, then compass to front/back/left/right, then sizes. A step a site change
  // touched comes out as { t, a: 1 } so the page can mark it as adapted.
  const adapt = (id, text) => {
    let t = text;
    CHANGES.forEach((c, i) => { if ((c.id === id || c.id === '*') && t.includes(c.find)) { t = t.split(c.find).join(c.to); used.add(i); } });
    return { t: L.render(relative(t), params), a: t !== text };
  };
  const r = (t) => adapt(r.id, t).t;
  const rs = (t) => { const x = adapt(r.id, t); return x.a ? { t: x.t, a: 1 } : x.t; };
  (function add(ids) {
    for (const id of ids) {
      if (procs[id]) continue;
      const p = reg.get(id);
      if (!p) throw new Error(`no procedure ${id}`);
      r.id = id;
      procs[id] = {
        title: r(p.title), purpose: r(p.purpose),
        pre: p.preconditions.map(rs), checks: p.checks.map(rs), safety: p.safety.map(rs),
        steps: p.steps.map((s) => (L.isCall(s) ? { call: s.call, times: s.times || 1, note: s.note ? r(s.note) : '' } : rs(s))),
        // A picture search for each material this step gathers, shown as a small link.
        photos: p.produces.materials.map((m) => ({ name: r(C.MATERIALS[m.id].name).split(/[,:]/)[0], url: photos.url(m.id) })).filter((x) => x.url),
      };
      add(L.callsOf(p));
    }
  })(ORDER);
  const unused = CHANGES.filter((c, i) => !used.has(i));
  return { ORDER, PROCS: procs, unused };
}

const out = ({ ORDER, PROCS }) => `// Generated by build.js from ../procedures and site.js. Don't edit by hand.\nwindow.DESIGN = ${JSON.stringify({ ORDER, PROCS }, null, 1)};\n`;
if (require.main === module) {
  const d = build();
  if (d.unused.length) throw new Error('site changes that match nothing: ' + d.unused.map((c) => c.find).join(' | '));
  fs.writeFileSync(path.join(__dirname, 'design.js'), out(d));
}
module.exports = { build, out, ORDER };

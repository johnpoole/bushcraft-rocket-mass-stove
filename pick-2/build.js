// Writes design.js: the shelter and stove instructions from ../procedures, in the build order
// on the shelter page, with every size filled in, so the checklist works with no signal.
// Run from the repo root after changing a procedure: node pick-2/build.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const L = require('../engine/lib.js');
const reg = L.byId(require('../procedures/index.js').load());
const params = require('../procedures/project.js').params();

// The build order from shelter/index.html, with the camp tools made first.
const ORDER = ['plan.make-tools', 'shelter.choose-site', 'shelter.frame', 'shelter.roof-insulate', 'shelter.walls',
  'plan.stove-stage-one', 'stove.first-firing', 'shelter.fit-out', 'plan.stove-stage-two', 'shelter.earth-skirt', 'shelter.snow-bank'];

function build() {
  const procs = {};
  const r = (t) => L.render(t, params);
  (function add(ids) {
    for (const id of ids) {
      if (procs[id]) continue;
      const p = reg.get(id);
      if (!p) throw new Error(`no procedure ${id}`);
      procs[id] = {
        title: r(p.title), purpose: r(p.purpose),
        pre: p.preconditions.map(r), checks: p.checks.map(r), safety: p.safety.map(r),
        steps: p.steps.map((s) => (L.isCall(s) ? { call: s.call, times: s.times || 1, note: s.note ? r(s.note) : '' } : r(s))),
      };
      add(L.callsOf(p));
    }
  })(ORDER);
  return { ORDER, PROCS: procs };
}

const out = (d) => `// Generated by build.js from ../procedures. Don't edit by hand.\nwindow.DESIGN = ${JSON.stringify(d, null, 1)};\n`;
if (require.main === module) fs.writeFileSync(path.join(__dirname, 'design.js'), out(build()));
module.exports = { build, out, ORDER };
